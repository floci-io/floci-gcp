package io.floci.gcp.services.credentials;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.floci.gcp.config.EmulatorConfig;
import io.floci.gcp.services.iam.IamService;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Inject;
import jakarta.ws.rs.core.Response;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.PublicKey;
import java.security.Signature;
import java.time.Clock;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Base64;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;

/**
 * The OAuth 2.0 token endpoint's JWT bearer grant, as described in
 * https://developers.google.com/identity/protocols/oauth2/service-account. In IAM enforce mode the
 * assertion is verified against the service account's user-managed keys and its Google-managed key, and
 * the token acts as that account; otherwise any assertion gets an unrecognized token, as before.
 */
@ApplicationScoped
public class OAuthTokenService {

    static final String JWT_BEARER_GRANT_TYPE = "urn:ietf:params:oauth:grant-type:jwt-bearer";
    static final String INVALID_SIGNATURE = "Invalid JWT Signature.";
    static final String INVALID_TIMEFRAME = "Invalid JWT: Token must be a short-lived token (60 minutes) and in a "
            + "reasonable timeframe. Check your iat and exp values in the JWT claim.";
    static final String INVALID_SCOPE = "Invalid OAuth scope or ID token audience provided.";
    // The messages below are not in Google's documentation: they are what https://oauth2.googleapis.com/token
    // answered on 2026-11-12 (floci-io/floci-gcp#644).
    static final String ACCOUNT_NOT_FOUND = "Invalid grant: account not found";
    static final String FAILED_AUDIENCE_CHECK = "Invalid JWT: Failed audience check.";
    static final String ISSUED_AT_NOT_SET = "Invalid JWT: iat (issued at) is not set.";
    static final String EXPIRATION_NOT_SET = "Invalid JWT: exp (expiration time) is not set.";
    static final String SCOPE_NOT_A_STRING = "Empty or missing scope not allowed.";
    /** Google documents that it refuses an {@code exp} more than 65 minutes after {@code iat}. */
    static final long MAX_ASSERTION_LIFETIME_SECONDS = 65 * 60;
    /**
     * How far ahead of the clock {@code iat} may be. Google refuses an {@code iat} 10 minutes ahead and
     * accepts one 2 minutes ahead (measured in review); 5 minutes is the time skew Google's own token
     * verifier allows by default ({@code IdTokenVerifier.DEFAULT_TIME_SKEW_SECONDS} in google-oauth-java-client).
     */
    static final long MAX_CLOCK_SKEW_SECONDS = 5 * 60;
    static final long TOKEN_LIFETIME_SECONDS = 3600;
    private static final Set<String> GOOGLE_AUDIENCES = Set.of(
            "https://oauth2.googleapis.com/token", "https://www.googleapis.com/oauth2/v4/token");
    private static final ObjectMapper MAPPER = new ObjectMapper();
    /** Generated by {@code tools/regen_oauth_scopes.py} from Google's API discovery documents. */
    static final String SCOPE_CATALOG = "oauth/oauth-scopes.json";
    private static final Set<String> GOOGLE_SCOPES = loadScopes();

    private final EmulatorConfig config;
    private final CredentialTokenService tokens;
    private final Instance<IamService> accounts;
    private final Clock clock;

    @Inject
    public OAuthTokenService(EmulatorConfig config, CredentialTokenService tokens, Instance<IamService> accounts) {
        this.config = config;
        this.tokens = tokens;
        this.accounts = accounts;
        this.clock = Clock.systemUTC();
    }

    /** {@code requestUrl} is where the client sent the assertion, which it may name as the audience. */
    public Response exchange(String grantType, String assertion, String requestUrl) {
        if (!JWT_BEARER_GRANT_TYPE.equals(grantType)) {
            return oauthError("unsupported_grant_type", "Unsupported grant type");
        }
        if (assertion == null || assertion.isBlank()) {
            return oauthError("invalid_grant", "Invalid JWT bearer token request");
        }
        if (config.services().iam().authorizationMode() != EmulatorConfig.IamAuthorizationMode.ENFORCE) {
            return tokenResponse(CredentialTokenService.FLOCI_TOKEN_PREFIX + UUID.randomUUID(), TOKEN_LIFETIME_SECONDS);
        }
        return verifiedExchange(assertion, requestUrl);
    }

    /**
     * Checks in the order Google does, so an assertion with several faults gets Google's answer: the
     * account, the audience, the timeframe and an empty scope before the signature, and the scopes'
     * names last.
     */
    private Response verifiedExchange(String assertion, String requestUrl) {
        String[] parts = assertion.split("\\.", -1);
        if (parts.length != 3) {
            return oauthError("invalid_request", "Bad Request");
        }
        JsonNode header;
        JsonNode claims;
        byte[] signature;
        try {
            header = MAPPER.readTree(Base64.getUrlDecoder().decode(parts[0]));
            claims = MAPPER.readTree(Base64.getUrlDecoder().decode(parts[1]));
            signature = Base64.getUrlDecoder().decode(parts[2]);
        } catch (IllegalArgumentException | IOException e) {
            return oauthError("invalid_request", "Bad Request");
        }
        if (header == null || !header.isObject() || claims == null || !claims.isObject()) {
            return oauthError("invalid_request", "Bad Request");
        }
        String email = claims.path("iss").isTextual() ? claims.get("iss").asText() : null;
        Optional<Map<String, PublicKey>> keys = email == null ? Optional.empty()
                : accounts.get().publicKeys(email, clock.instant());
        if (keys.isEmpty()) {
            return oauthError("invalid_grant", ACCOUNT_NOT_FOUND);
        }
        String audience = claims.path("aud").isTextual() ? claims.get("aud").asText() : null;
        if (audience == null || !(GOOGLE_AUDIENCES.contains(audience) || audience.equals(requestUrl))) {
            return oauthError("invalid_grant", FAILED_AUDIENCE_CHECK);
        }
        JsonNode issuedAt = claims.get("iat");
        JsonNode expiresAt = claims.get("exp");
        if (issuedAt == null || issuedAt.isNull()) {
            return oauthError("invalid_grant", ISSUED_AT_NOT_SET);
        }
        if (expiresAt == null || expiresAt.isNull()) {
            return oauthError("invalid_grant", EXPIRATION_NOT_SET);
        }
        if (!issuedAt.canConvertToLong() || !expiresAt.canConvertToLong()) {
            return oauthError("invalid_grant", INVALID_TIMEFRAME);
        }
        long iat = issuedAt.asLong();
        long exp = expiresAt.asLong();
        long now = clock.instant().getEpochSecond();
        if (exp < iat || exp - iat > MAX_ASSERTION_LIFETIME_SECONDS || exp <= now
                || iat > now + MAX_CLOCK_SKEW_SECONDS) {
            return oauthError("invalid_grant", INVALID_TIMEFRAME);
        }
        // Google answers invalid_scope when "No scopes were requested (empty list of scopes), or one of the
        // requested scopes doesn't exist (i.e. is invalid)."
        JsonNode scope = claims.get("scope");
        if (scope != null && scope.isArray()) {
            return oauthError("invalid_scope", SCOPE_NOT_A_STRING);
        }
        if (scope == null || !scope.isTextual() || scope.asText().isBlank()) {
            return oauthError("invalid_scope", INVALID_SCOPE);
        }
        byte[] signedInput = (parts[0] + "." + parts[1]).getBytes(StandardCharsets.US_ASCII);
        if (!"RS256".equals(header.path("alg").asText(null))
                || !verifies(keys.get(), header.path("kid").asText(null), signedInput, signature)) {
            return oauthError("invalid_grant", INVALID_SIGNATURE);
        }
        if (!Arrays.stream(scope.asText().trim().split("\\s+")).allMatch(GOOGLE_SCOPES::contains)) {
            return oauthError("invalid_scope", INVALID_SCOPE);
        }
        StoredCredentialToken token = tokens.mintImpersonatedToken(email,
                clock.instant().plusSeconds(TOKEN_LIFETIME_SECONDS));
        return tokenResponse(token.getTokenValue(), TOKEN_LIFETIME_SECONDS);
    }

    /** Google: "If an incorrect Key ID is specified, all keys associated with the service account are tried." */
    private static boolean verifies(Map<String, PublicKey> keys, String keyId, byte[] signedInput, byte[] signature) {
        List<PublicKey> candidates = new ArrayList<>();
        if (keyId != null && keys.containsKey(keyId)) {
            candidates.add(keys.get(keyId));
        }
        candidates.addAll(keys.values());
        for (PublicKey key : candidates) {
            try {
                Signature verifier = Signature.getInstance("SHA256withRSA");
                verifier.initVerify(key);
                verifier.update(signedInput);
                if (verifier.verify(signature)) {
                    return true;
                }
            } catch (GeneralSecurityException expected) {
                // A signature that does not parse for this key verifies nothing; the next key is tried.
                continue;
            }
        }
        return false;
    }

    private static Set<String> loadScopes() {
        try (InputStream in = OAuthTokenService.class.getClassLoader().getResourceAsStream(SCOPE_CATALOG)) {
            if (in == null) {
                throw new IllegalStateException("Missing bundled resource " + SCOPE_CATALOG);
            }
            Set<String> scopes = new HashSet<>();
            MAPPER.readTree(in).path("scopes").forEach(node -> scopes.add(node.asText()));
            return Set.copyOf(scopes);
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot read " + SCOPE_CATALOG, e);
        }
    }

    private static Response tokenResponse(String accessToken, long expiresIn) {
        return Response.ok(Map.of(
                "access_token", accessToken,
                "token_type", "Bearer",
                "expires_in", expiresIn))
                .build();
    }

    private static Response oauthError(String error, String description) {
        Map<String, String> body = new LinkedHashMap<>();
        body.put("error", error);
        body.put("error_description", description);
        return Response.status(Response.Status.BAD_REQUEST)
                .entity(body)
                .build();
    }
}
